-- =====================================================================
-- ELO CAMPUS - ESQUEMA DO BANCO DE DADOS (PostgreSQL)
-- =====================================================================
--
-- Sistema de gestão de equipamentos: cadastro de equipamentos e
-- categorias, empréstimos, devoluções, reservas, manutenções e
-- histórico de movimentações.
--
-- Requisitos
--   PostgreSQL 13 ou superior (testado no 18).
--
-- Como usar
--   Execute este arquivo em um banco de dados VAZIO:
--
--     psql -h <host> -U <usuario> -d <banco> -v ON_ERROR_STOP=1 -f schema.sql
--
--   O script inteiro roda em uma única transação: se qualquer comando
--   falhar, nada é criado. Ele NÃO apaga dados e NÃO deve ser executado
--   em um banco que já possui estas tabelas.
--
-- Convenções
--   * Chaves primárias: BIGINT gerado automaticamente (IDENTITY).
--   * Datas e horas: TIMESTAMPTZ (com fuso horário), gravadas em UTC.
--   * Status e estados: textos em minúsculas, sem acento, validados por
--     CHECK. Os valores são os mesmos usados pelo backend (Python).
--   * Registros não são apagados: o backend usa "ativo = FALSE" ou o
--     status "baixado" para preservar o histórico.
--
-- Usuário inicial
--   Este script não cria contas nem senhas. Depois de executá-lo,
--   crie o primeiro administrador conforme a seção "Pós-instalação"
--   no final do arquivo.
-- =====================================================================

BEGIN;

SET client_encoding = 'UTF8';


-- =====================================================================
-- 1. SOLICITANTES
--    Pessoas que pegam equipamentos emprestados ou fazem reservas
--    (alunos, servidores, professores etc.). Nem todo solicitante
--    tem conta de acesso ao sistema.
-- =====================================================================

CREATE TABLE solicitantes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(120) NOT NULL,
    tipo        VARCHAR(30)  NOT NULL,
    setor       VARCHAR(100),
    email       VARCHAR(150),
    telefone    VARCHAR(30),
    ativo       BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),

    CONSTRAINT solicitantes_nome_nao_vazio
        CHECK (BTRIM(nome) <> ''),
    CONSTRAINT solicitantes_tipo_valido
        CHECK (tipo IN ('aluno', 'servidor', 'professor', 'tecnico', 'externo'))
);

COMMENT ON TABLE  solicitantes IS
    'Pessoas que solicitam empréstimos e reservas de equipamentos.';
COMMENT ON COLUMN solicitantes.tipo IS
    'aluno | servidor | professor | tecnico | externo. Somente solicitantes dos tipos aluno e professor podem criar conta pelo autocadastro.';
COMMENT ON COLUMN solicitantes.ativo IS
    'FALSE = desativado. Solicitantes inativos não podem fazer empréstimos nem reservas.';


-- =====================================================================
-- 2. USUÁRIOS
--    Contas de acesso ao sistema.
--      admin     -> administração completa
--      operador  -> operação do dia a dia (empréstimos, devoluções...)
--      aluno     -> conta vinculada a um solicitante do tipo aluno
--      professor -> conta vinculada a um solicitante do tipo professor
-- =====================================================================

CREATE TABLE usuarios (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(120) NOT NULL,
    email           VARCHAR(150) NOT NULL,
    senha_hash      VARCHAR(255) NOT NULL,
    papel           VARCHAR(20)  NOT NULL DEFAULT 'operador',
    ativo           BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    solicitante_id  BIGINT REFERENCES solicitantes (id),

    CONSTRAINT usuarios_nome_nao_vazio
        CHECK (BTRIM(nome) <> ''),
    CONSTRAINT usuarios_papel_valido
        CHECK (papel IN ('admin', 'operador', 'aluno', 'professor')),
    CONSTRAINT usuarios_usuario_final_tem_solicitante
        CHECK (papel NOT IN ('aluno', 'professor') OR solicitante_id IS NOT NULL)
);

-- O login compara o e-mail sem diferenciar maiúsculas de minúsculas
-- (LOWER(email) = LOWER(%s)); a unicidade segue a mesma regra.
CREATE UNIQUE INDEX usuarios_email_unico
    ON usuarios (LOWER(email));

-- Cada solicitante pode ter no máximo uma conta.
CREATE UNIQUE INDEX usuarios_solicitante_unico
    ON usuarios (solicitante_id)
    WHERE solicitante_id IS NOT NULL;

COMMENT ON TABLE  usuarios IS
    'Contas de acesso ao sistema.';
COMMENT ON COLUMN usuarios.senha_hash IS
    'Hash gerado por werkzeug.security.generate_password_hash. Nunca armazene a senha em texto.';
COMMENT ON COLUMN usuarios.papel IS
    'admin | operador | aluno | professor.';
COMMENT ON COLUMN usuarios.solicitante_id IS
    'Obrigatório para os papéis aluno e professor. Liga a conta ao cadastro de solicitante.';


-- =====================================================================
-- 3. CATEGORIAS
-- =====================================================================

CREATE TABLE categorias (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(80) NOT NULL,
    descricao   TEXT,
    ativo       BOOLEAN     NOT NULL DEFAULT TRUE,

    CONSTRAINT categorias_nome_nao_vazio
        CHECK (BTRIM(nome) <> '')
);

-- Impede categorias duplicadas como "Notebook" e "notebook".
CREATE UNIQUE INDEX categorias_nome_unico
    ON categorias (LOWER(nome));

COMMENT ON TABLE  categorias IS
    'Agrupamento de equipamentos (ex.: Notebooks, Projetores).';
COMMENT ON COLUMN categorias.ativo IS
    'Só pode ser desativada quando não houver equipamentos não baixados na categoria.';


-- =====================================================================
-- 4. EQUIPAMENTOS
--    estado_conservacao: condição física do equipamento.
--    status: situação operacional, controlada pelo backend.
--      disponivel -> pode ser emprestado ou reservado
--      emprestado -> está em um empréstimo em andamento
--      manutencao -> em manutenção (ou danificado aguardando reparo)
--      baixado    -> retirado do patrimônio; estado final
-- =====================================================================

CREATE TABLE equipamentos (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                VARCHAR(120) NOT NULL,
    numero_patrimonio   VARCHAR(60),
    categoria_id        BIGINT       NOT NULL REFERENCES categorias (id),
    setor               VARCHAR(100),
    localizacao         VARCHAR(150),
    estado_conservacao  VARCHAR(30)  NOT NULL DEFAULT 'bom',
    status              VARCHAR(30)  NOT NULL DEFAULT 'disponivel',
    qr_code             VARCHAR(255),
    observacoes         TEXT,
    criado_em           TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    elegibilidade       VARCHAR(40)  NOT NULL DEFAULT 'todos',

    CONSTRAINT equipamentos_nome_nao_vazio
        CHECK (BTRIM(nome) <> ''),
    CONSTRAINT equipamentos_patrimonio_unico
        UNIQUE (numero_patrimonio),
    CONSTRAINT equipamentos_estado_valido
        CHECK (estado_conservacao IN ('novo', 'bom', 'regular', 'danificado')),
    CONSTRAINT equipamentos_status_valido
        CHECK (status IN ('disponivel', 'emprestado', 'manutencao', 'baixado')),
    CONSTRAINT equipamentos_elegibilidade_valida
        CHECK (elegibilidade IN ('todos', 'somente_funcionarios'))
);

CREATE INDEX equipamentos_categoria_idx ON equipamentos (categoria_id);
CREATE INDEX equipamentos_status_idx    ON equipamentos (status);

COMMENT ON TABLE  equipamentos IS
    'Equipamentos patrimoniados disponíveis para empréstimo e reserva.';
COMMENT ON COLUMN equipamentos.numero_patrimonio IS
    'Opcional, mas único quando informado.';
COMMENT ON COLUMN equipamentos.status IS
    'disponivel | emprestado | manutencao | baixado. Controlado pelo backend, não pelo cliente.';
COMMENT ON COLUMN equipamentos.elegibilidade IS
    'todos | somente_funcionarios. Reservado para regra de elegibilidade (ainda não aplicada pelo backend).';


-- =====================================================================
-- 5. EMPRÉSTIMOS
--    Um empréstimo tem um ou mais itens (tabela itens_emprestimo).
--    Ele é concluído automaticamente quando todos os itens são
--    devolvidos.
-- =====================================================================

CREATE TABLE emprestimos (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante_id           BIGINT      NOT NULL REFERENCES solicitantes (id),
    usuario_responsavel_id   BIGINT      NOT NULL REFERENCES usuarios (id),
    data_emprestimo          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_prevista_devolucao  TIMESTAMPTZ NOT NULL,
    status                   VARCHAR(30) NOT NULL DEFAULT 'em_andamento',
    observacoes              TEXT,
    criado_em                TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT emprestimos_status_valido
        CHECK (status IN ('em_andamento', 'concluido', 'cancelado')),
    CONSTRAINT emprestimos_datas_validas
        CHECK (data_prevista_devolucao >= data_emprestimo)
);

CREATE INDEX emprestimos_solicitante_idx ON emprestimos (solicitante_id);
CREATE INDEX emprestimos_responsavel_idx ON emprestimos (usuario_responsavel_id);
CREATE INDEX emprestimos_status_idx      ON emprestimos (status);

COMMENT ON TABLE  emprestimos IS
    'Empréstimos de equipamentos a solicitantes.';
COMMENT ON COLUMN emprestimos.usuario_responsavel_id IS
    'Usuário (operador/admin) que registrou o empréstimo.';
COMMENT ON COLUMN emprestimos.status IS
    'em_andamento | concluido | cancelado. Passa a concluido quando todos os itens são devolvidos.';


-- =====================================================================
-- 6. ITENS DO EMPRÉSTIMO
--    Cada linha é um equipamento dentro de um empréstimo. A devolução
--    é registrada por item.
-- =====================================================================

CREATE TABLE itens_emprestimo (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emprestimo_id        BIGINT      NOT NULL REFERENCES emprestimos (id) ON DELETE CASCADE,
    equipamento_id       BIGINT      NOT NULL REFERENCES equipamentos (id),
    data_devolucao       TIMESTAMPTZ,
    estado_na_retirada   VARCHAR(30),
    estado_na_devolucao  VARCHAR(30),
    observacoes          TEXT,

    CONSTRAINT itens_emprestimo_equipamento_unico
        UNIQUE (emprestimo_id, equipamento_id),
    CONSTRAINT itens_emprestimo_estado_retirada_valido
        CHECK (estado_na_retirada IS NULL
               OR estado_na_retirada IN ('novo', 'bom', 'regular', 'danificado')),
    CONSTRAINT itens_emprestimo_estado_devolucao_valido
        CHECK (estado_na_devolucao IS NULL
               OR estado_na_devolucao IN ('novo', 'bom', 'regular', 'danificado')),
    CONSTRAINT itens_emprestimo_devolucao_completa
        CHECK ((data_devolucao IS NULL) = (estado_na_devolucao IS NULL))
);

-- Um equipamento só pode estar em UM empréstimo não devolvido por vez.
-- Proteção final contra registros duplicados em acessos simultâneos.
CREATE UNIQUE INDEX itens_emprestimo_equipamento_em_aberto
    ON itens_emprestimo (equipamento_id)
    WHERE data_devolucao IS NULL;

CREATE INDEX itens_emprestimo_equipamento_idx ON itens_emprestimo (equipamento_id);

COMMENT ON TABLE  itens_emprestimo IS
    'Equipamentos de cada empréstimo e o registro individual da devolução.';
COMMENT ON COLUMN itens_emprestimo.data_devolucao IS
    'NULL = item ainda não devolvido.';
COMMENT ON COLUMN itens_emprestimo.estado_na_retirada IS
    'Cópia de equipamentos.estado_conservacao no momento do empréstimo.';


-- =====================================================================
-- 7. MANUTENÇÕES
--    Ao abrir uma manutenção, o equipamento passa para "manutencao".
--    Ao finalizar, volta para "disponivel" (exceto se estiver baixado).
-- =====================================================================

CREATE TABLE manutencoes (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id          BIGINT      NOT NULL REFERENCES equipamentos (id),
    usuario_responsavel_id  BIGINT      REFERENCES usuarios (id),
    descricao_problema      TEXT        NOT NULL,
    data_abertura           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    data_conclusao          TIMESTAMPTZ,
    status                  VARCHAR(30) NOT NULL DEFAULT 'aberta',
    solucao                 TEXT,
    observacoes             TEXT,

    CONSTRAINT manutencoes_descricao_nao_vazia
        CHECK (BTRIM(descricao_problema) <> ''),
    CONSTRAINT manutencoes_status_valido
        CHECK (status IN ('aberta', 'em_andamento', 'concluida', 'cancelada')),
    CONSTRAINT manutencoes_conclusao_completa
        CHECK (status <> 'concluida'
               OR (data_conclusao IS NOT NULL AND solucao IS NOT NULL)),
    CONSTRAINT manutencoes_datas_validas
        CHECK (data_conclusao IS NULL OR data_conclusao >= data_abertura)
);

-- Cada equipamento pode ter no máximo UMA manutenção em aberto.
CREATE UNIQUE INDEX manutencoes_uma_aberta_por_equipamento
    ON manutencoes (equipamento_id)
    WHERE status IN ('aberta', 'em_andamento');

CREATE INDEX manutencoes_equipamento_idx ON manutencoes (equipamento_id);

COMMENT ON TABLE  manutencoes IS
    'Manutenções de equipamentos (abertura e finalização).';
COMMENT ON COLUMN manutencoes.status IS
    'aberta | em_andamento | concluida | cancelada.';


-- =====================================================================
-- 8. HISTÓRICO DE MOVIMENTAÇÕES
--    Registro cronológico do que aconteceu com cada equipamento.
--    O backend grava automaticamente "emprestimo" e "devolucao";
--    outros tipos podem ser lançados manualmente pela API.
-- =====================================================================

CREATE TABLE historico_movimentacoes (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipamento_id     BIGINT      NOT NULL REFERENCES equipamentos (id),
    usuario_id         BIGINT      REFERENCES usuarios (id),
    emprestimo_id      BIGINT      REFERENCES emprestimos (id),
    tipo_movimentacao  VARCHAR(40) NOT NULL,
    data_movimentacao  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    descricao          TEXT,

    CONSTRAINT historico_tipo_nao_vazio
        CHECK (BTRIM(tipo_movimentacao) <> '')
);

CREATE INDEX historico_equipamento_idx ON historico_movimentacoes (equipamento_id);
CREATE INDEX historico_emprestimo_idx  ON historico_movimentacoes (emprestimo_id);
CREATE INDEX historico_data_idx
    ON historico_movimentacoes (data_movimentacao DESC, id DESC);

COMMENT ON TABLE  historico_movimentacoes IS
    'Linha do tempo das movimentações de cada equipamento.';
COMMENT ON COLUMN historico_movimentacoes.tipo_movimentacao IS
    'Texto livre. Valores gravados pelo backend: emprestimo, devolucao.';


-- =====================================================================
-- 9. RESERVAS
--    Fluxo de status:
--      pendente -> aprovada | rejeitada | cancelada
--      aprovada -> cancelada
--    O status "concluida" existe para uso futuro.
-- =====================================================================

CREATE TABLE reservas (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante_id          BIGINT      NOT NULL REFERENCES solicitantes (id),
    usuario_responsavel_id  BIGINT      REFERENCES usuarios (id),
    data_inicio             TIMESTAMPTZ NOT NULL,
    data_fim                TIMESTAMPTZ NOT NULL,
    status                  VARCHAR(20) NOT NULL DEFAULT 'pendente',
    observacoes             TEXT,
    criado_em               TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT reservas_datas_validas
        CHECK (data_fim > data_inicio),
    CONSTRAINT reservas_status_valido
        CHECK (status IN ('pendente', 'aprovada', 'rejeitada', 'cancelada', 'concluida'))
);

CREATE INDEX reservas_solicitante_idx ON reservas (solicitante_id);
-- Acelera a verificação de conflitos de período entre reservas ativas.
CREATE INDEX reservas_periodo_ativas_idx
    ON reservas (data_inicio, data_fim)
    WHERE status IN ('pendente', 'aprovada');

COMMENT ON TABLE  reservas IS
    'Reservas de equipamentos para um período futuro.';
COMMENT ON COLUMN reservas.status IS
    'pendente | aprovada | rejeitada | cancelada | concluida.';


-- =====================================================================
-- 10. ITENS DA RESERVA
-- =====================================================================

CREATE TABLE itens_reserva (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id      BIGINT NOT NULL REFERENCES reservas (id) ON DELETE CASCADE,
    equipamento_id  BIGINT NOT NULL REFERENCES equipamentos (id),

    CONSTRAINT itens_reserva_equipamento_unico
        UNIQUE (reserva_id, equipamento_id)
);

CREATE INDEX itens_reserva_equipamento_idx ON itens_reserva (equipamento_id);

COMMENT ON TABLE itens_reserva IS
    'Equipamentos incluídos em cada reserva.';


COMMIT;


